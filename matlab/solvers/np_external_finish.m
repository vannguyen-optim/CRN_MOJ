function out=np_external_finish(P,x,o,name,status,native,X,hist,elapsed,log,timer)
% Common ORIGINAL certificate, independent of native stopping tests.
[u,R,ok,cw]=np_certificate(P,x,[],o);[f,~,~,F,margin]=np_eval(P,x);
S=sign(X(P.alpha>0,:));ch=find(any(diff(S,1,2)~=0,1));last=0;
if ~isempty(ch),last=ch(end);end
out=struct('method',name,'status',status,'termination_reason',status, ...
 'success',ok&&R<=o.tol&&np_feas(P,x)<=o.feas_tol,'x',x,'u',u, ...
 'residual',R,'feasibility',np_feas(P,x),'objective',f,'F',F, ...
 'selected',nnz(P.alpha>0&x~=0),'iterations',size(hist,1),'history',hist, ...
 'elapsed',elapsed,'iterates',X,'native_residual',native,'native_history',{log}, ...
 'seconds',toc(timer),'support_changes',numel(ch),'last_support_change',last, ...
 'counts',struct('total_qp',np_work_budget('used'),'candidate_qp',0, ...
 'fallback_qp',0,'certificate_qp',cw,'linear_solves',0), ...
 'min_margin',min([abs(margin);Inf]),'raw_polishing',{{}});
end
